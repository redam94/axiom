def test_report_and_theme_round_trip(template: Report) -> None:
    assert Report.from_dict(template.to_dict()) == template
    assert Report.from_json(template.to_json()) == template
    theme = Theme(name="house", accent_color="#123456", palette=("#111111", "#222222"))
    assert Theme.from_dict(theme.to_dict()) == theme
    # restyling is a different report, and the hash says so
    assert template.model_copy(update={"theme": theme}).content_hash() != template.content_hash()


def test_theme_validates_its_colours_and_geometry() -> None:
    with pytest.raises(ValueError, match="hex colour"):
        Theme(accent_color="blue")
    with pytest.raises(ValueError, match="palette colours"):
        Theme(palette=("#fff",))
    with pytest.raises(ValueError, match="page must be a paper size"):
        Theme(page="widescreen")
    with pytest.raises(ValueError, match="slide must be a slide size"):
        Theme(slide="a4")
    theme = Theme()
    assert theme.page_geometry() == (612.0, 792.0)
    assert theme.slide_geometry() == (960.0, 540.0)
    assert theme.heading_size(1) > theme.heading_size(3)
    assert theme.heading_size(9) == theme.heading_size(3)
    assert theme.colour(0) == theme.colour(len(theme.palette))


def test_resolved_text_distinguishes_headings(context: dict[str, object]) -> None:
    report = Report(
        name="r",
        title="t",
        sections=(Section(title="s", blocks=(Heading(text="H", level=1), Paragraph(text="p"))),),
    )
    out = resolve(report, context)
    assert not isinstance(out, Unsupported)
    heading, paragraph = out.sections[0].blocks
    assert isinstance(heading, ResolvedText) and heading.is_heading and heading.level == 1
    assert isinstance(paragraph, ResolvedText) and not paragraph.is_heading


def test_dimensions_are_untouched_by_reporting(band: ResponseBand) -> None:
    """A band keeps its dimension through a report; nothing here rescales a number."""
    assert band.dimension == D.outcome
    report = Report(
        name="r", title="t", sections=(Section(title="s", blocks=(Figure(source="b"),)),)
    )
    out = resolve(report, {"b": band})
    assert not isinstance(out, Unsupported)
    assert band.dimension == D.outcome
