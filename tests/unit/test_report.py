# -- the template language -----------------------------------------------------------------


def test_placeholders_are_parsed_not_guessed() -> None:
    assert placeholders("plain") == ()
    assert placeholders("{a} and {b:.2f} and {a}") == ("a", "b")
    assert placeholders("{{literal}} braces") == ()
    assert placeholders("{obj.field}") == ("obj",)
    with pytest.raises(ValueError, match="positional placeholders"):
        placeholders("{} unnamed")


def test_a_report_holds_no_data_only_the_names_of_data(template: Report) -> None:
    """The property that makes it a template: sources, in reading order, no values."""
    assert template.sources() == (
        "as_of",
        "effect",
        "contrast",
        "response",
        "mass",
        "arms",
        "ledger",
    )
    text = template.to_json()
    assert "2026-08-21" not in text and "7.25" not in text


def test_missing_names_every_absent_key_at_once(template: Report) -> None:
    assert missing(template, {}) == template.sources()
    assert missing(template, {"as_of": "x", "effect": 1.0}) == (
        "contrast",
        "response",
        "mass",
        "arms",
        "ledger",
    )


def test_the_same_template_renders_two_contexts_and_keeps_its_hash(
    template: Report, context: dict[str, object]
) -> None:
    """'Automated and repeated': layout is the template's identity, data is not."""
    first = resolve(template, context)
    second = resolve(template, {**context, "effect": 9.5, "as_of": "2026-11-01"})
    assert not isinstance(first, Unsupported) and not isinstance(second, Unsupported)
    assert first.source_hash == second.source_hash == template.content_hash()
    assert first.sections[0].blocks[0] != second.sections[0].blocks[0]
    assert "7.2" in first.sections[0].blocks[0].text
    assert "9.5" in second.sections[0].blocks[0].text


def test_a_missing_source_is_a_typed_failure_not_an_exception(template: Report) -> None:
    out = resolve(template, {"as_of": "x"})
    assert isinstance(out, Unsupported)
    assert "contrast" in out.reason and "ledger" in out.reason
    assert out.missing == missing(template, {"as_of": "x"})


def test_a_present_but_unusable_source_names_the_block(context: dict[str, object]) -> None:
    """A gap in the data is Unsupported; a mistake in the template is an exception."""
    report = Report(
        name="r", title="t", sections=(Section(title="s", blocks=(Figure(source="arms"),)),)
    )
    with pytest.raises(ValueError, match="figure block 'arms' needs a plotly Figure"):
        resolve(report, context)
    report = Report(
        name="r",
        title="t",
        sections=(Section(title="s", blocks=(Metric(source="arms", label="x"),)),),
    )
    with pytest.raises(ValueError, match="metric block 'arms' needs a number"):
        resolve(report, context)
    report = Report(
        name="r", title="t", sections=(Section(title="s", blocks=(Table(source="effect"),)),)
    )
    with pytest.raises(ValueError, match="table block 'effect' needs a DataFrame"):
        resolve(report, {"effect": 1.0})


def test_a_table_truncates_loudly(context: dict[str, object]) -> None:
    block = Table(source="arms", max_rows=2)
    report = Report(name="r", title="t", sections=(Section(title="s", blocks=(block,)),))
    out = resolve(report, context)
    assert not isinstance(out, Unsupported)
    table = out.sections[0].blocks[0]
    assert len(table.rows) == 2
    assert table.truncated == 1
    with pytest.raises(ValueError, match="has no column"):
        resolve(
            Report(
                name="r",
                title="t",
                sections=(Section(title="s", blocks=(Table(source="arms", columns=("nope",)),)),),
            ),
            context,
        )


def test_page_breaks_become_positions_not_blocks() -> None:
    report = Report(
        name="r",
        title="t",
        sections=(
            Section(
                title="s",
                blocks=(Paragraph(text="a"), PageBreak(), Paragraph(text="b")),
            ),
        ),
    )
    out = resolve(report, {})
    assert not isinstance(out, Unsupported)
    assert len(out.sections[0].blocks) == 2
    assert out.sections[0].breaks == frozenset({1})


