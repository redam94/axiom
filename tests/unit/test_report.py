def test_a_surface_figure_carries_its_band(template: Report, context: dict[str, object]) -> None:
    """A ResponseBand source is drawn through viz, which cannot draw one without its band."""
    out = resolve(template, context)
    assert not isinstance(out, Unsupported)
    figure = next(b for s in out.sections for b in s.blocks if isinstance(b, ResolvedFigure))
    assert len(figure.figure.data) == 2
    assert figure.figure.data[0].fill == "toself"
    assert "90%" in figure.caption


@pytest.mark.parametrize(
    ("value", "has_interval"),
    [
        (eti(np.linspace(0.0, 2.0, 100), 0.9), True),
        (3.5, False),
    ],
)
def test_a_metric_shows_its_interval_when_it_has_one(value: object, has_interval: bool) -> None:
    report = Report(
        name="r",
        title="t",
        sections=(Section(title="s", blocks=(Metric(source="v", label="Effect", unit="mmHg"),)),),
    )
    out = resolve(report, {"v": value})
    assert not isinstance(out, Unsupported)
    metric = out.sections[0].blocks[0]
    assert isinstance(metric, ResolvedMetric)
    assert metric.unit == "mmHg" and "mmHg" in metric.text
    if has_interval:
        assert isinstance(metric.interval, Interval)
        assert "90%" in metric.interval_text and "ETI" in metric.interval_text
    else:
        assert metric.interval is None and metric.interval_text == ""


def test_a_summary_and_an_estimand_result_both_keep_their_interval() -> None:
    from axiom.core import summarize

    summary = summarize(np.linspace(1.0, 3.0, 200), definition="hdi", mass=0.8)
    report = Report(
        name="r", title="t", sections=(Section(title="s", blocks=(Metric(source="v", label="L"),)),)
    )
    out = resolve(report, {"v": summary})
    assert not isinstance(out, Unsupported)
    metric = out.sections[0].blocks[0]
    assert metric.interval is not None
    assert metric.interval.mass == 0.8 and metric.interval.definition == "hdi"


def test_nothing_in_the_block_vocabulary_can_suppress_an_interval() -> None:
    """There is no field anywhere that turns uncertainty off. That is the point."""
    forbidden = {"show_interval", "with_interval", "hide_interval", "band", "show_band"}
    for cls in (Metric, Figure, Table, Paragraph, Heading):
        assert not forbidden & set(cls.model_fields), cls.__name__


def test_the_theme_cannot_hide_a_band() -> None:
    with pytest.raises(ValueError):
        Theme(band_opacity=0.0)
    assert Theme(band_opacity=0.05).band_opacity == 0.05


