def test_the_builder_is_immutable_and_composes() -> None:
    base = ReportBuilder("r", "T").section("One")
    left = base.paragraph("left")
    right = base.paragraph("right")
    assert left.build().sections[0].blocks[0].text == "left"
    assert right.build().sections[0].blocks[0].text == "right"
    assert base.build().sections[0].blocks == ()


def test_the_builder_refuses_a_block_with_no_section() -> None:
    with pytest.raises(ValueError, match="open a section before adding blocks"):
        ReportBuilder("r", "T").paragraph("orphan")
    with pytest.raises(ValueError, match="at least one section"):
        ReportBuilder("r", "T").build()


def test_a_report_refuses_duplicate_section_titles() -> None:
    with pytest.raises(ValueError, match="duplicate section title"):
        ReportBuilder("r", "T").section("Same").paragraph("a").section("Same").build()


